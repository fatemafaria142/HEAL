import csv
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from sqlalchemy import create_engine, select, Integer
from sqlalchemy.orm import sessionmaker
from sqlalchemy.dialects import postgresql

from database.models import Base
from database.db_init import create_synthetic_data

FIXTURE_PATH = Path(__file__).resolve().parent / "fixtures" / "synclin_database_snapshot.sql"
CSV_DIR = Path(__file__).resolve().parent / "fixtures" / "csv"
STAGING_DB = Path(__file__).resolve().parent / "fixtures" / "_staging.sqlite"


def _serial_pk_columns(table):
    for col in table.primary_key.columns:
        if isinstance(col.type, Integer) and col.autoincrement is not False:
            yield col


def build():
    if STAGING_DB.exists():
        STAGING_DB.unlink()

    engine = create_engine(f"sqlite:///{STAGING_DB}")
    Base.metadata.create_all(engine)

    Session = sessionmaker(bind=engine)
    session = Session()
    create_synthetic_data(session)
    session.close()

    lines = [
        "-- Auto-generated by database/build_fixture.py — DO NOT edit by hand.",
        "-- Static snapshot of the SynClin-SQL synthetic dataset (seeder: database/db_init.py, seed=42).",
        "-- Replayed as-is by `python -m database.import_db`; regenerate only after a schema/seeder change.",
        "BEGIN;",
    ]
    row_count = 0
    with engine.connect() as conn:
        for table in Base.metadata.sorted_tables:
            rows = conn.execute(select(table)).mappings().all()
            for row in rows:
                stmt = table.insert().values(**dict(row))
                compiled = stmt.compile(
                    dialect=postgresql.dialect(),
                    compile_kwargs={"literal_binds": True},
                )
                lines.append(f"{compiled};")
                row_count += 1

        for table in Base.metadata.sorted_tables:
            for pk in _serial_pk_columns(table):
                lines.append(
                    f"SELECT setval(pg_get_serial_sequence('{table.name}', '{pk.name}'), "
                    f"COALESCE((SELECT MAX({pk.name}) FROM {table.name}), 1), "
                    f"(SELECT MAX({pk.name}) FROM {table.name}) IS NOT NULL);"
                )

        CSV_DIR.mkdir(parents=True, exist_ok=True)
        for table in Base.metadata.sorted_tables:
            cols = [c.name for c in table.columns]
            rows = conn.execute(select(table)).mappings().all()
            with (CSV_DIR / f"{table.name}.csv").open("w", newline="", encoding="utf-8") as f:
                writer = csv.writer(f)
                writer.writerow(cols)
                writer.writerows([row[c] for c in cols] for row in rows)

    lines.append("COMMIT;")

    FIXTURE_PATH.write_text("\n".join(lines) + "\n")
    STAGING_DB.unlink()
    print(f"Wrote {row_count} rows across {len(Base.metadata.sorted_tables)} tables -> {FIXTURE_PATH}")
    print(f"Wrote per-table CSVs -> {CSV_DIR}")


if __name__ == "__main__":
    build()
